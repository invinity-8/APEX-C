/**
 * Printed / flattened Aurora Builder PDFs (e.g. "Lucia_Lvl3.pdf" exported without form fields) contain the
 * character's values only as positioned page text – plain text parsing cannot tell "11" (Strength) from "11"
 * (Dexterity). Aurora always uses the same page templates, so every value is matched to the form field whose
 * rectangle contains it (layout taken from the fillable sample, see scripts/gen-aurora-layout.ts). The result is
 * the same field map a fillable Aurora PDF yields, so the normal Aurora mapper reads it.
 */
import layout from './auroraLayout.json';
import type { Extracted, PositionedText } from './map';

type Field = [name: string, x0: number, y0: number, x1: number, y1: number, checkbox: 0 | 1];
interface TemplatePage {
  labels: Array<[string, number, number]>;
  fields: Field[];
}
const PAGES = (layout as unknown as { pages: TemplatePage[] }).pages;

const AURORA_MARK = /generated by the Aurora Builder/i;
const norm = (s: string) => s.replace(/\s+/g, ' ').trim().toUpperCase();

/** Score how well a page's text matches a template page: share of the template's labels found nearby. */
function matchScore(items: PositionedText[], tpl: TemplatePage): number {
  if (!tpl.labels.length) return 0;
  const byText = new Map<string, PositionedText[]>();
  for (const i of items) {
    const k = norm(i.str);
    (byText.get(k) ?? byText.set(k, []).get(k)!).push(i);
  }
  let hit = 0;
  for (const [s, x, y] of tpl.labels) if ((byText.get(norm(s)) ?? []).some((i) => Math.abs(i.x - x) < 3 && Math.abs(i.y - y) < 3)) hit++;
  return hit / tpl.labels.length;
}

function isTemplateLabel(i: PositionedText, tpl: TemplatePage): boolean {
  const s = norm(i.str);
  return tpl.labels.some(([l, x, y]) => norm(l) === s && Math.abs(i.x - x) < 3 && Math.abs(i.y - y) < 3);
}

export interface FlatAuroraResult {
  fields: Record<string, string>;
  checkboxes: Record<string, boolean>;
  /** Page texts without the runs that were assigned to form fields (static sheet text, features …). */
  pageTexts: string[];
  pagesMatched: number;
}

/**
 * Rebuilds Aurora form fields from positioned text. Returns null if the PDF is not a field-less Aurora sheet
 * (or its pages do not match the known templates).
 */
export function reconstructAuroraFields(x: Extracted): FlatAuroraResult | null {
  if (Object.keys(x.fields).length > 0 || !x.positioned?.length || !AURORA_MARK.test(x.text)) return null;
  const fields: Record<string, string> = {};
  const checkboxes: Record<string, boolean> = {};
  const used = new Map<number, number>(); // template page → times used (repeated spell / equipment pages)
  let pagesMatched = 0;
  const pageTexts: string[] = [];

  x.positioned.forEach((items, pageIndex) => {
    const assigned = new Set<PositionedText>();
    pageTexts[pageIndex] = x.pageTexts?.[pageIndex] ?? '';
    let best = -1;
    let bestScore = 0;
    PAGES.forEach((tpl, t) => {
      const s = matchScore(items, tpl);
      if (s > bestScore) [best, bestScore] = [t, s];
    });
    if (best < 0 || bestScore < 0.5) return; // not a known Aurora page (cards, notes …)
    pagesMatched++;
    const tpl = PAGES[best];
    const occurrence = (used.get(best) ?? 0) + 1;
    used.set(best, occurrence);

    const collected = new Map<string, PositionedText[]>();
    for (const i of items) {
      if (isTemplateLabel(i, tpl)) continue;
      // reference point: a little inside the text run's baseline box
      const px = i.x + Math.min(2, i.w / 2);
      const py = i.y + i.h * 0.3;
      // A run belongs to the field that contains its reference point; within a 1.5 pt tolerance the nearest
      // rectangle wins (stacked rows touch each other), then the smaller one (nested boxes).
      let hit: Field | null = null;
      let best = [Infinity, Infinity];
      for (const f of tpl.fields) {
        const [, x0, y0, x1, y1] = f;
        const dx = Math.max(x0 - px, 0, px - x1);
        const dy = Math.max(y0 - py, 0, py - y1);
        if (dx > 1.5 || dy > 1.5) continue;
        const score = [Math.hypot(dx, dy), (x1 - x0) * (y1 - y0)];
        if (score[0] < best[0] || (score[0] === best[0] && score[1] < best[1])) [hit, best] = [f, score];
      }
      if (!hit) continue;
      assigned.add(i);
      if (hit[5] === 1) {
        checkboxes[hit[0]] = true; // a check mark glyph inside a checkbox
        continue;
      }
      (collected.get(hit[0]) ?? collected.set(hit[0], []).get(hit[0])!).push(i);
    }

    // Spell pages carry the class and a page counter in their field names (spells_1:0_:Druid:1).
    const classField = tpl.fields.find(([n]) => n.startsWith('spellcasting_class:'))?.[0];
    const classValue = classField ? join(collected.get(classField) ?? []) : '';
    const rename = (name: string) => {
      let n = name;
      if (classField) {
        const tplClass = classField.split(':')[1];
        const cls = classValue.replace(/[^A-Za-z]/g, '') || tplClass;
        n = n.replace(`:${tplClass}:`, `:${cls}:`);
      }
      return occurrence > 1 ? n.replace(/:(\d+)$/, (_, d: string) => `:${Number(d) + occurrence - 1}`) : n;
    };
    for (const [name, runs] of collected) {
      const v = join(runs);
      if (v) fields[rename(name)] = v;
    }
    pageTexts[pageIndex] = textWithout(items, assigned);
  });
  return pagesMatched ? { fields, checkboxes, pageTexts, pagesMatched } : null;
}

/** Page text (same line breaking as pdfCore) without the given runs. */
function textWithout(items: PositionedText[], skip: Set<PositionedText>): string {
  const lines: string[] = [];
  let line = '';
  for (const i of items) {
    if (!skip.has(i)) line += i.str + ' ';
    if (i.eol && line.trim()) {
      lines.push(line);
      line = '';
    }
  }
  if (line.trim()) lines.push(line);
  return lines.map((l) => l.replace(/[ \t]+/g, ' ').trim()).join('\n');
}

/** Joins the runs of one field in reading order (top to bottom, left to right). */
function join(runs: PositionedText[]): string {
  const sorted = [...runs].sort((a, b) => (Math.abs(a.y - b.y) > Math.min(a.h, b.h) * 0.5 ? b.y - a.y : a.x - b.x));
  let out = '';
  let prev: PositionedText | null = null;
  for (const r of sorted) {
    if (prev) out += Math.abs(prev.y - r.y) > Math.min(prev.h, r.h) * 0.5 ? '\n' : prev.x + prev.w + 0.5 < r.x ? ' ' : '';
    out += r.str;
    prev = r;
  }
  return out.replace(/[ \t]+/g, ' ').trim();
}
